/*
 * parser.c - the Higgson parser: reads tokens and writes assembly.
 *
 * One function per grammar rule (recursive descent). Each rule emits the
 * code for what it parsed as it goes; an expression always leaves its
 * value in eax, using the stack for the left side of an operator.
 */
#include "higgson/parser.h"
#include "higgson/hg.h"
#include "higgson/util.h"

#define INT_MAX_VALUE 2147483647L

static const char* hg_token_name(hg_token_type_t type) {
    switch (type) {
        case TOK_EOF:      return "EOF";
        case TOK_NEWLINE:  return "NEWLINE";
        case TOK_NUMBER:   return "NUMBER";
        case TOK_IDENT:    return "IDENT";
        case TOK_STRING:   return "STRING";
        case TOK_LET:      return "LET";
        case TOK_GOTO:     return "GOTO";
        case TOK_LABEL:    return "LABEL";
        case TOK_PRINT:    return "PRINT";
        case TOK_INPUT:    return "INPUT";
        case TOK_IF:       return "IF";
        case TOK_ELSE:     return "ELSE";
        case TOK_THEN:     return "THEN";
        case TOK_ENDIF:    return "ENDIF";
        case TOK_WHILE:    return "WHILE";
        case TOK_REPEAT:   return "REPEAT";
        case TOK_ENDWHILE: return "ENDWHILE";
        case TOK_EQ:       return "EQ";
        case TOK_PLUS:     return "PLUS";
        case TOK_MINUS:    return "MINUS";
        case TOK_SLASH:    return "SLASH";
        case TOK_STAR:     return "STAR";
        case TOK_EQEQ:     return "EQEQ";
        case TOK_LT:       return "LT";
        case TOK_NOTE:     return "NOTEQ";
        case TOK_LTE:      return "LTEQ";
        case TOK_GT:       return "GT";
        case TOK_GTE:      return "GTEQ";
    }
    return "UNKNOWN";
}

static int hg_set_contains(const hg_name_set_t* set, const char* name) {
    for (int i = 0; i < set->count; ++i) {
        if (hg_util_strcmp(set->items[i], name) == 0) {
            return 1;
        }
    }
    return 0;
}

static void hg_set_add(hg_name_set_t* set, const char* name) {
    if (hg_set_contains(set, name)) {
        return;
    }
    if (set->count >= HG_MAX_NAMES) {
        hg_error(0, "Too many names (max %d)", HG_MAX_NAMES);
    }
    set->items[set->count++] = name;
}

static int hg_check_token(hg_parser_t* parser, hg_token_type_t type) {
    return parser->curr_token.type == type;
}

static void hg_next_token(hg_parser_t* parser) {
    parser->curr_token = parser->peek_token;
    parser->peek_token = hg_get_token(parser->lexer);
}

static void hg_match(hg_parser_t* parser, hg_token_type_t type) {
    if (!hg_check_token(parser, type)) {
        hg_error(parser->curr_token.line, "Expected %s, got %s",
                         hg_token_name(type), hg_token_name(parser->curr_token.type));
    }
    hg_next_token(parser);
}

static void hg_statement(hg_parser_t* parser);
static void hg_comparison(hg_parser_t* parser);
static int  hg_is_comparison_operator(hg_parser_t* parser);
static void hg_expression(hg_parser_t* parser);
static void hg_term(hg_parser_t* parser);
static void hg_unary(hg_parser_t* parser);
static void hg_primary(hg_parser_t* parser);
static void hg_nl(hg_parser_t* parser);

void hg_parser_init(hg_parser_t* parser, hg_lexer_t* lexer, hg_emitter_t* emitter) {
    parser->lexer = lexer;
    parser->emitter = emitter;
    parser->symbols.count = 0;
    parser->labels_declared.count = 0;
    parser->labels_gotoed.count = 0;

    hg_next_token(parser);
    hg_next_token(parser);
}

void hg_parser_program(hg_parser_t* parser) {
    hg_emitter_t* e = parser->emitter;

    hg_header_line(e, "; generated by higgson");
    hg_header_line(e, "SYS_PRINT        equ 0");
    hg_header_line(e, "SYS_PRINT_NUMBER equ 5");
    hg_header_line(e, "");
    hg_header_line(e, "_start:");
    hg_data_line(e, "_nl: db 10, 0");

    while (hg_check_token(parser, TOK_NEWLINE)) {
        hg_next_token(parser);
    }

    while (!hg_check_token(parser, TOK_EOF)) {
        hg_statement(parser);
    }

    hg_emit_line(e, "    xor eax, eax");
    hg_emit_line(e, "    ret");
    hg_emit_line(e, "");

    for (int i = 0; i < parser->labels_gotoed.count; ++i) {
        const char* label = parser->labels_gotoed.items[i];
        if (!hg_set_contains(&parser->labels_declared, label)) {
            hg_error(parser->labels_gotoed_line[i], "Attempting to GOTO to undeclared label: %s", label);
        }
    }
}

static void hg_emit_print_newline(hg_emitter_t* e) {
    hg_emit_line(e, "    mov eax, SYS_PRINT");
    hg_emit_line(e, "    mov ebx, _nl");
    hg_emit_line(e, "    int 0x80");
}

static void hg_statement(hg_parser_t* parser) {
    hg_emitter_t* e = parser->emitter;

    if (hg_check_token(parser, TOK_PRINT)) {
        hg_next_token(parser);

        if (hg_check_token(parser, TOK_STRING)) {
            int label = hg_new_label(e);
            hg_data_line(e, "S%d: db \"%s\", 10, 0", label, parser->curr_token.text);
            hg_emit_line(e, "    mov eax, SYS_PRINT");
            hg_emit_line(e, "    mov ebx, S%d", label);
            hg_emit_line(e, "    int 0x80");
            hg_next_token(parser);
        }
        else {
            hg_expression(parser);
            hg_emit_line(e, "    mov ebx, eax");
            hg_emit_line(e, "    mov eax, SYS_PRINT_NUMBER");
            hg_emit_line(e, "    int 0x80");
            hg_emit_print_newline(e);
        }
    }

    else if (hg_check_token(parser, TOK_IF)) {
        int end = hg_new_label(e);
        hg_next_token(parser);
        hg_comparison(parser);

        hg_match(parser, TOK_THEN);
        hg_nl(parser);
        hg_emit_line(e, "    cmp eax, 0");
        hg_emit_line(e, "    je L%d", end);

        while (!hg_check_token(parser, TOK_ENDIF)) {
            hg_statement(parser);
        }

        hg_match(parser, TOK_ENDIF);
        hg_emit_line(e, "L%d:", end);
    }

    else if (hg_check_token(parser, TOK_WHILE)) {
        int top = hg_new_label(e);
        int end = hg_new_label(e);
        hg_next_token(parser);
        hg_emit_line(e, "L%d:", top);
        hg_comparison(parser);

        hg_match(parser, TOK_REPEAT);
        hg_nl(parser);
        hg_emit_line(e, "    cmp eax, 0");
        hg_emit_line(e, "    je L%d", end);

        while (!hg_check_token(parser, TOK_ENDWHILE)) {
            hg_statement(parser);
        }

        hg_match(parser, TOK_ENDWHILE);
        hg_emit_line(e, "    jmp L%d", top);
        hg_emit_line(e, "L%d:", end);
    }

    else if (hg_check_token(parser, TOK_LABEL)) {
        hg_next_token(parser);

        if (hg_set_contains(&parser->labels_declared, parser->curr_token.text)) {
            hg_error(parser->curr_token.line, "Label already exists: %s", parser->curr_token.text);
        }
        hg_set_add(&parser->labels_declared, parser->curr_token.text);

        hg_emit_line(e, "_l_%s:", parser->curr_token.text);
        hg_match(parser, TOK_IDENT);
    }

    else if (hg_check_token(parser, TOK_GOTO)) {
        hg_next_token(parser);
        if (!hg_set_contains(&parser->labels_gotoed, parser->curr_token.text)) {
            parser->labels_gotoed_line[parser->labels_gotoed.count] = parser->curr_token.line;
        }
        hg_set_add(&parser->labels_gotoed, parser->curr_token.text);
        hg_emit_line(e, "    jmp _l_%s", parser->curr_token.text);
        hg_match(parser, TOK_IDENT);
    }

    else if (hg_check_token(parser, TOK_LET)) {
        hg_next_token(parser);
        const char* name = parser->curr_token.text;

        if (!hg_set_contains(&parser->symbols, name)) {
            hg_set_add(&parser->symbols, name);
            hg_data_line(e, "_v_%s: dd 0", name);
        }

        hg_match(parser, TOK_IDENT);
        hg_match(parser, TOK_EQ);

        hg_expression(parser);
        hg_emit_line(e, "    mov [_v_%s], eax", name);
    }

    else if (hg_check_token(parser, TOK_INPUT)) {
        hg_error(parser->curr_token.line, "INPUT is not supported on planckOS yet");
    }

    else {
        hg_error(parser->curr_token.line, "Invalid statement at %s (%s)",
                         parser->curr_token.text, hg_token_name(parser->curr_token.type));
    }

    hg_nl(parser);
}

static const char* hg_jump_for(hg_token_type_t type) {
    switch (type) {
        case TOK_GT:   return "jg";
        case TOK_GTE:  return "jge";
        case TOK_LT:   return "jl";
        case TOK_LTE:  return "jle";
        case TOK_EQEQ: return "je";
        case TOK_NOTE: return "jne";
        default:       return "jmp";
    }
}

static void hg_emit_pop_left(hg_emitter_t* e) {
    hg_emit_line(e, "    mov ecx, eax");
    hg_emit_line(e, "    pop eax");
}

static void hg_comparison(hg_parser_t* parser) {
    hg_emitter_t* e = parser->emitter;

    hg_expression(parser);

    if (!hg_is_comparison_operator(parser)) {
        hg_error(parser->curr_token.line, "Expected comparison operator at: %s", parser->curr_token.text);
    }

    while (hg_is_comparison_operator(parser)) {
        hg_token_type_t op = parser->curr_token.type;
        int done = hg_new_label(e);

        hg_next_token(parser);
        hg_emit_line(e, "    push eax");
        hg_expression(parser);
        hg_emit_pop_left(e);

        hg_emit_line(e, "    cmp eax, ecx");
        hg_emit_line(e, "    mov eax, 1");
        hg_emit_line(e, "    %s L%d", hg_jump_for(op), done);
        hg_emit_line(e, "    mov eax, 0");
        hg_emit_line(e, "L%d:", done);
    }
}

static int hg_is_comparison_operator(hg_parser_t* parser) {
    return hg_check_token(parser, TOK_GT) || hg_check_token(parser, TOK_GTE) ||
           hg_check_token(parser, TOK_LT) || hg_check_token(parser, TOK_LTE) ||
           hg_check_token(parser, TOK_EQEQ) || hg_check_token(parser, TOK_NOTE);
}

static void hg_expression(hg_parser_t* parser) {
    hg_emitter_t* e = parser->emitter;

    hg_term(parser);

    while (hg_check_token(parser, TOK_PLUS) || hg_check_token(parser, TOK_MINUS)) {
        hg_token_type_t op = parser->curr_token.type;
        hg_next_token(parser);

        hg_emit_line(e, "    push eax");
        hg_term(parser);
        hg_emit_pop_left(e);

        if (op == TOK_PLUS) {
            hg_emit_line(e, "    add eax, ecx");
        }
        else {
            hg_emit_line(e, "    sub eax, ecx");
        }
    }
}

static void hg_term(hg_parser_t* parser) {
    hg_emitter_t* e = parser->emitter;

    hg_unary(parser);

    while (hg_check_token(parser, TOK_STAR) || hg_check_token(parser, TOK_SLASH)) {
        hg_token_type_t op = parser->curr_token.type;
        hg_next_token(parser);

        hg_emit_line(e, "    push eax");
        hg_unary(parser);
        hg_emit_pop_left(e);

        if (op == TOK_STAR) {
            hg_emit_line(e, "    mul ecx");
        }
        else {
            hg_emit_line(e, "    cdq");
            hg_emit_line(e, "    idiv ecx");
        }
    }
}

static void hg_unary(hg_parser_t* parser) {
    int negate = 0;

    if (hg_check_token(parser, TOK_PLUS) || hg_check_token(parser, TOK_MINUS)) {
        negate = hg_check_token(parser, TOK_MINUS);
        hg_next_token(parser);
    }

    hg_primary(parser);

    if (negate) {
        hg_emit_line(parser->emitter, "    neg eax");
    }
}

/* The value of a number token. Our own strtol: no C library here. */
static long hg_parse_number(hg_parser_t* parser, const char* text) {
    long value = 0;

    for (const char* p = text; *p; p++) {
        if (*p == '.') {
            hg_error(parser->curr_token.line, "planckOS has no decimals yet, use whole numbers: %s", text);
        }
        if (value > (INT_MAX_VALUE - (*p - '0')) / 10) {
            hg_error(parser->curr_token.line, "Number too big: %s", text);
        }
        value = value * 10 + (*p - '0');
    }
    return value;
}

static void hg_primary(hg_parser_t* parser) {
    hg_emitter_t* e = parser->emitter;

    if (hg_check_token(parser, TOK_NUMBER)) {
        const char* text = parser->curr_token.text;
        long value = hg_parse_number(parser, text);

        hg_emit_line(e, "    mov eax, %ld", value);
        hg_next_token(parser);
    }
    else if (hg_check_token(parser, TOK_IDENT)) {
        if (!hg_set_contains(&parser->symbols, parser->curr_token.text)) {
            hg_error(parser->curr_token.line, "Referencing variable before assignment: %s",
                             parser->curr_token.text);
        }
        hg_emit_line(e, "    mov eax, [_v_%s]", parser->curr_token.text);
        hg_next_token(parser);
    }
    else {
        hg_error(parser->curr_token.line, "Unexpected token at %s", parser->curr_token.text);
    }
}

static void hg_nl(hg_parser_t* parser) {
    hg_match(parser, TOK_NEWLINE);

    while (hg_check_token(parser, TOK_NEWLINE)) {
        hg_next_token(parser);
    }
}
