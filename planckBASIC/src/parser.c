#include "parser.h"

#include <stdarg.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <errno.h>

static void pcl_parser_abort(const char* fmt, ...) {
    va_list args;
    va_start(args, fmt);
    fprintf(stderr, "PCL PARSER ERROR: ");
    vfprintf(stderr, fmt, args);
    fprintf(stderr, "\n");
    va_end(args);
    exit(-1);
}

static const char* pcl_token_name(pcl_token_type_t type) {
    switch (type) {
        case TOK_EOF:      return "EOF";
        case TOK_NEWLINE:  return "NEWLINE";
        case TOK_NUMBER:   return "NUMBER";
        case TOK_IDENT:    return "IDENT";
        case TOK_STRING:   return "STRING";
        case TOK_LET:      return "LET";
        case TOK_GOTO:     return "GOTO";
        case TOK_LABEL:    return "LABEL";
        case TOK_PRINT:    return "PRINT";
        case TOK_INPUT:    return "INPUT";
        case TOK_IF:       return "IF";
        case TOK_ELSE:     return "ELSE";
        case TOK_THEN:     return "THEN";
        case TOK_ENDIF:    return "ENDIF";
        case TOK_WHILE:    return "WHILE";
        case TOK_REPEAT:   return "REPEAT";
        case TOK_ENDWHILE: return "ENDWHILE";
        case TOK_EQ:       return "EQ";
        case TOK_PLUS:     return "PLUS";
        case TOK_MINUS:    return "MINUS";
        case TOK_SLASH:    return "SLASH";
        case TOK_STAR:     return "STAR";
        case TOK_EQEQ:     return "EQEQ";
        case TOK_LT:       return "LT";
        case TOK_NOTE:     return "NOTEQ";
        case TOK_LTE:      return "LTEQ";
        case TOK_GT:       return "GT";
        case TOK_GTE:      return "GTEQ";
    }
    return "UNKNOWN";
}

static int pcl_set_contains(const pcl_name_set_t* set, const char* name) {
    for (int i = 0; i < set->count; ++i) {
        if (strcmp(set->items[i], name) == 0) {
            return 1;
        }
    }
    return 0;
}

static void pcl_set_add(pcl_name_set_t* set, const char* name) {
    if (pcl_set_contains(set, name)) {
        return;
    }
    if (set->count >= PCL_MAX_NAMES) {
        pcl_parser_abort("Too many names (max %d)", PCL_MAX_NAMES);
    }
    set->items[set->count++] = name;
}

static int pcl_check_token(pcl_parser_t* parser, pcl_token_type_t type) {
    return parser->curr_token.type == type;
}

static int pcl_check_peek(pcl_parser_t* parser, pcl_token_type_t type) {
    return parser->peek_token.type == type;
}

static void pcl_next_token(pcl_parser_t* parser) {
    parser->curr_token = parser->peek_token;
    parser->peek_token = pcl_get_token(parser->lexer);
}

static void pcl_match(pcl_parser_t* parser, pcl_token_type_t type) {
    if (!pcl_check_token(parser, type)) {
        pcl_parser_abort("Expected %s, got %s",
                         pcl_token_name(type), pcl_token_name(parser->curr_token.type));
    }
    pcl_next_token(parser);
}

static void pcl_statement(pcl_parser_t* parser);
static void pcl_comparison(pcl_parser_t* parser);
static int  pcl_is_comparison_operator(pcl_parser_t* parser);
static void pcl_expression(pcl_parser_t* parser);
static void pcl_term(pcl_parser_t* parser);
static void pcl_unary(pcl_parser_t* parser);
static void pcl_primary(pcl_parser_t* parser);
static void pcl_nl(pcl_parser_t* parser);

void pcl_parser_init(pcl_parser_t* parser, pcl_lexer_t* lexer, pcl_emitter_t* emitter) {
    parser->lexer = lexer;
    parser->emitter = emitter;
    parser->symbols.count = 0;
    parser->labels_declared.count = 0;
    parser->labels_gotoed.count = 0;

    pcl_next_token(parser);
    pcl_next_token(parser);
}

void pcl_parser_program(pcl_parser_t* parser) {
    pcl_emitter_t* e = parser->emitter;

    pcl_header_line(e, "; generated by pclc");
    pcl_header_line(e, "SYS_PRINT        equ 0");
    pcl_header_line(e, "SYS_PRINT_NUMBER equ 5");
    pcl_header_line(e, "");
    pcl_header_line(e, "_start:");
    pcl_data_line(e, "_nl: db 10, 0");

    while (pcl_check_token(parser, TOK_NEWLINE)) {
        pcl_next_token(parser);
    }

    while (!pcl_check_token(parser, TOK_EOF)) {
        pcl_statement(parser);
    }

    pcl_emit_line(e, "    xor eax, eax");
    pcl_emit_line(e, "    ret");
    pcl_emit_line(e, "");

    for (int i = 0; i < parser->labels_gotoed.count; ++i) {
        const char* label = parser->labels_gotoed.items[i];
        if (!pcl_set_contains(&parser->labels_declared, label)) {
            pcl_parser_abort("Attempting to GOTO to undeclared label: %s", label);
        }
    }
}

static void pcl_emit_print_newline(pcl_emitter_t* e) {
    pcl_emit_line(e, "    mov eax, SYS_PRINT");
    pcl_emit_line(e, "    mov ebx, _nl");
    pcl_emit_line(e, "    int 0x80");
}

static void pcl_statement(pcl_parser_t* parser) {
    pcl_emitter_t* e = parser->emitter;

    if (pcl_check_token(parser, TOK_PRINT)) {
        pcl_next_token(parser);

        if (pcl_check_token(parser, TOK_STRING)) {
            int label = pcl_new_label(e);
            pcl_data_line(e, "S%d: db \"%s\", 10, 0", label, parser->curr_token.text);
            pcl_emit_line(e, "    mov eax, SYS_PRINT");
            pcl_emit_line(e, "    mov ebx, S%d", label);
            pcl_emit_line(e, "    int 0x80");
            pcl_next_token(parser);
        }
        else {
            pcl_expression(parser);
            pcl_emit_line(e, "    mov ebx, eax");
            pcl_emit_line(e, "    mov eax, SYS_PRINT_NUMBER");
            pcl_emit_line(e, "    int 0x80");
            pcl_emit_print_newline(e);
        }
    }

    else if (pcl_check_token(parser, TOK_IF)) {
        int end = pcl_new_label(e);
        pcl_next_token(parser);
        pcl_comparison(parser);

        pcl_match(parser, TOK_THEN);
        pcl_nl(parser);
        pcl_emit_line(e, "    cmp eax, 0");
        pcl_emit_line(e, "    je L%d", end);

        while (!pcl_check_token(parser, TOK_ENDIF)) {
            pcl_statement(parser);
        }

        pcl_match(parser, TOK_ENDIF);
        pcl_emit_line(e, "L%d:", end);
    }

    else if (pcl_check_token(parser, TOK_WHILE)) {
        int top = pcl_new_label(e);
        int end = pcl_new_label(e);
        pcl_next_token(parser);
        pcl_emit_line(e, "L%d:", top);
        pcl_comparison(parser);

        pcl_match(parser, TOK_REPEAT);
        pcl_nl(parser);
        pcl_emit_line(e, "    cmp eax, 0");
        pcl_emit_line(e, "    je L%d", end);

        while (!pcl_check_token(parser, TOK_ENDWHILE)) {
            pcl_statement(parser);
        }

        pcl_match(parser, TOK_ENDWHILE);
        pcl_emit_line(e, "    jmp L%d", top);
        pcl_emit_line(e, "L%d:", end);
    }

    else if (pcl_check_token(parser, TOK_LABEL)) {
        pcl_next_token(parser);

        if (pcl_set_contains(&parser->labels_declared, parser->curr_token.text)) {
            pcl_parser_abort("Label already exists: %s", parser->curr_token.text);
        }
        pcl_set_add(&parser->labels_declared, parser->curr_token.text);

        pcl_emit_line(e, "_l_%s:", parser->curr_token.text);
        pcl_match(parser, TOK_IDENT);
    }

    else if (pcl_check_token(parser, TOK_GOTO)) {
        pcl_next_token(parser);
        pcl_set_add(&parser->labels_gotoed, parser->curr_token.text);
        pcl_emit_line(e, "    jmp _l_%s", parser->curr_token.text);
        pcl_match(parser, TOK_IDENT);
    }

    else if (pcl_check_token(parser, TOK_LET)) {
        pcl_next_token(parser);
        const char* name = parser->curr_token.text;

        if (!pcl_set_contains(&parser->symbols, name)) {
            pcl_set_add(&parser->symbols, name);
            pcl_data_line(e, "_v_%s: dd 0", name);
        }

        pcl_match(parser, TOK_IDENT);
        pcl_match(parser, TOK_EQ);

        pcl_expression(parser);
        pcl_emit_line(e, "    mov [_v_%s], eax", name);
    }

    else if (pcl_check_token(parser, TOK_INPUT)) {
        pcl_parser_abort("INPUT is not supported on planckOS yet");
    }

    else {
        pcl_parser_abort("Invalid statement at %s (%s)",
                         parser->curr_token.text, pcl_token_name(parser->curr_token.type));
    }

    pcl_nl(parser);
}

static const char* pcl_jump_for(pcl_token_type_t type) {
    switch (type) {
        case TOK_GT:   return "jg";
        case TOK_GTE:  return "jge";
        case TOK_LT:   return "jl";
        case TOK_LTE:  return "jle";
        case TOK_EQEQ: return "je";
        case TOK_NOTE: return "jne";
        default:       return "jmp";
    }
}

static void pcl_emit_pop_left(pcl_emitter_t* e) {
    pcl_emit_line(e, "    mov ecx, eax");
    pcl_emit_line(e, "    pop eax");
}

static void pcl_comparison(pcl_parser_t* parser) {
    pcl_emitter_t* e = parser->emitter;

    pcl_expression(parser);

    if (!pcl_is_comparison_operator(parser)) {
        pcl_parser_abort("Expected comparison operator at: %s", parser->curr_token.text);
    }

    while (pcl_is_comparison_operator(parser)) {
        pcl_token_type_t op = parser->curr_token.type;
        int done = pcl_new_label(e);

        pcl_next_token(parser);
        pcl_emit_line(e, "    push eax");
        pcl_expression(parser);
        pcl_emit_pop_left(e);

        pcl_emit_line(e, "    cmp eax, ecx");
        pcl_emit_line(e, "    mov eax, 1");
        pcl_emit_line(e, "    %s L%d", pcl_jump_for(op), done);
        pcl_emit_line(e, "    mov eax, 0");
        pcl_emit_line(e, "L%d:", done);
    }
}

static int pcl_is_comparison_operator(pcl_parser_t* parser) {
    return pcl_check_token(parser, TOK_GT) || pcl_check_token(parser, TOK_GTE) ||
           pcl_check_token(parser, TOK_LT) || pcl_check_token(parser, TOK_LTE) ||
           pcl_check_token(parser, TOK_EQEQ) || pcl_check_token(parser, TOK_NOTE);
}

static void pcl_expression(pcl_parser_t* parser) {
    pcl_emitter_t* e = parser->emitter;

    pcl_term(parser);

    while (pcl_check_token(parser, TOK_PLUS) || pcl_check_token(parser, TOK_MINUS)) {
        pcl_token_type_t op = parser->curr_token.type;
        pcl_next_token(parser);

        pcl_emit_line(e, "    push eax");
        pcl_term(parser);
        pcl_emit_pop_left(e);

        if (op == TOK_PLUS) {
            pcl_emit_line(e, "    add eax, ecx");
        }
        else {
            pcl_emit_line(e, "    sub eax, ecx");
        }
    }
}

static void pcl_term(pcl_parser_t* parser) {
    pcl_emitter_t* e = parser->emitter;

    pcl_unary(parser);

    while (pcl_check_token(parser, TOK_STAR) || pcl_check_token(parser, TOK_SLASH)) {
        pcl_token_type_t op = parser->curr_token.type;
        pcl_next_token(parser);

        pcl_emit_line(e, "    push eax");
        pcl_unary(parser);
        pcl_emit_pop_left(e);

        if (op == TOK_STAR) {
            pcl_emit_line(e, "    mul ecx");
        }
        else {
            pcl_emit_line(e, "    cdq");
            pcl_emit_line(e, "    idiv ecx");
        }
    }
}

static void pcl_unary(pcl_parser_t* parser) {
    int negate = 0;

    if (pcl_check_token(parser, TOK_PLUS) || pcl_check_token(parser, TOK_MINUS)) {
        negate = pcl_check_token(parser, TOK_MINUS);
        pcl_next_token(parser);
    }

    pcl_primary(parser);

    if (negate) {
        pcl_emit_line(parser->emitter, "    neg eax");
    }
}

static void pcl_primary(pcl_parser_t* parser) {
    pcl_emitter_t* e = parser->emitter;

    if (pcl_check_token(parser, TOK_NUMBER)) {
        const char* text = parser->curr_token.text;
        char* end;

        if (strchr(text, '.')) {
            pcl_parser_abort("planckOS has no decimals yet, use whole numbers: %s", text);
        }
        errno = 0;
        long value = strtol(text, &end, 10);
        if (errno == ERANGE || value > 2147483647L) {
            pcl_parser_abort("Number too big: %s", text);
        }

        pcl_emit_line(e, "    mov eax, %ld", value);
        pcl_next_token(parser);
    }
    else if (pcl_check_token(parser, TOK_IDENT)) {
        if (!pcl_set_contains(&parser->symbols, parser->curr_token.text)) {
            pcl_parser_abort("Referencing variable before assignment: %s",
                             parser->curr_token.text);
        }
        pcl_emit_line(e, "    mov eax, [_v_%s]", parser->curr_token.text);
        pcl_next_token(parser);
    }
    else {
        pcl_parser_abort("Unexpected token at %s", parser->curr_token.text);
    }
}

static void pcl_nl(pcl_parser_t* parser) {
    pcl_match(parser, TOK_NEWLINE);

    while (pcl_check_token(parser, TOK_NEWLINE)) {
        pcl_next_token(parser);
    }
}

void pcl_parser_program(pcl_parser_t* parser) {
    printf("PROGRAM\n");

    while (pcl_check_token(parser, TOK_NEWLINE)) {
        pcl_next_token(parser);
    }

    while (!pcl_check_token(parser, TOK_EOF)) {
        pcl_statement(parser);
    }

    for (int i = 0; i < parser->labels_gotoed.count; ++i) {
        const char* label = parser->labels_gotoed.items[i];
        if (!pcl_set_contains(&parser->labels_declared, label)) {
            pcl_parser_abort("Attempting to GOTO to undeclared label: %s", label);
        }
    }
}

static void pcl_statement(pcl_parser_t* parser) {
    if (pcl_check_token(parser, TOK_PRINT)) {
        printf("STATEMENT-PRINT\n");
        pcl_next_token(parser);

        if (pcl_check_token(parser, TOK_STRING)) {
            pcl_next_token(parser);
        }
        else {
            pcl_expression(parser);
        }
    }

    else if (pcl_check_token(parser, TOK_IF)) {
        printf("STATEMENT-IF\n");
        pcl_next_token(parser);
        pcl_comparison(parser);

        pcl_match(parser, TOK_THEN);
        pcl_nl(parser);

        while (!pcl_check_token(parser, TOK_ENDIF)) {
            pcl_statement(parser);
        }

        pcl_match(parser, TOK_ENDIF);
    }

    else if (pcl_check_token(parser, TOK_WHILE)) {
        printf("STATEMENT-WHILE\n");
        pcl_next_token(parser);
        pcl_comparison(parser);

        pcl_match(parser, TOK_REPEAT);
        pcl_nl(parser);

        while (!pcl_check_token(parser, TOK_ENDWHILE)) {
            pcl_statement(parser);
        }

        pcl_match(parser, TOK_ENDWHILE);
    }

    else if (pcl_check_token(parser, TOK_LABEL)) {
        printf("STATEMENT-LABEL\n");
        pcl_next_token(parser);

        if (pcl_set_contains(&parser->labels_declared, parser->curr_token.text)) {
            pcl_parser_abort("Label already exists: %s", parser->curr_token.text);
        }
        pcl_set_add(&parser->labels_declared, parser->curr_token.text);

        pcl_match(parser, TOK_IDENT);
    }

    else if (pcl_check_token(parser, TOK_GOTO)) {
        printf("STATEMENT-GOTO\n");
        pcl_next_token(parser);
        pcl_set_add(&parser->labels_gotoed, parser->curr_token.text);
        pcl_match(parser, TOK_IDENT);
    }

    else if (pcl_check_token(parser, TOK_LET)) {
        printf("STATEMENT-LET\n");
        pcl_next_token(parser);

        pcl_set_add(&parser->symbols, parser->curr_token.text);

        pcl_match(parser, TOK_IDENT);
        pcl_match(parser, TOK_EQ);

        pcl_expression(parser);
    }

    else if (pcl_check_token(parser, TOK_INPUT)) {
        printf("STATEMENT-INPUT\n");
        pcl_next_token(parser);

        pcl_set_add(&parser->symbols, parser->curr_token.text);

        pcl_match(parser, TOK_IDENT);
    }

    else {
        pcl_parser_abort("Invalid statement at %s (%s)",
                         parser->curr_token.text, pcl_token_name(parser->curr_token.type));
    }

    pcl_nl(parser);
}

static void pcl_comparison(pcl_parser_t* parser) {
    printf("COMPARISON\n");

    pcl_expression(parser);

    if (pcl_is_comparison_operator(parser)) {
        pcl_next_token(parser);
        pcl_expression(parser);
    }
    else {
        pcl_parser_abort("Expected comparison operator at: %s", parser->curr_token.text);
    }

    while (pcl_is_comparison_operator(parser)) {
        pcl_next_token(parser);
        pcl_expression(parser);
    }
}

static int pcl_is_comparison_operator(pcl_parser_t* parser) {
    return pcl_check_token(parser, TOK_GT) || pcl_check_token(parser, TOK_GTE) ||
           pcl_check_token(parser, TOK_LT) || pcl_check_token(parser, TOK_LTE) ||
           pcl_check_token(parser, TOK_EQEQ) || pcl_check_token(parser, TOK_NOTE);
}

static void pcl_expression(pcl_parser_t* parser) {
    printf("EXPRESSION\n");

    pcl_term(parser);

    while (pcl_check_token(parser, TOK_PLUS) || pcl_check_token(parser, TOK_MINUS)) {
        pcl_next_token(parser);
        pcl_term(parser);
    }
}

static void pcl_term(pcl_parser_t* parser) {
    printf("TERM\n");

    pcl_unary(parser);

    while (pcl_check_token(parser, TOK_STAR) || pcl_check_token(parser, TOK_SLASH)) {
        pcl_next_token(parser);
        pcl_unary(parser);
    }
}

static void pcl_unary(pcl_parser_t* parser) {
    printf("UNARY\n");

    if (pcl_check_token(parser, TOK_PLUS) || pcl_check_token(parser, TOK_MINUS)) {
        pcl_next_token(parser);
    }

    pcl_primary(parser);
}

static void pcl_primary(pcl_parser_t* parser) {
    printf("PRIMARY (%s)\n", parser->curr_token.text);

    if (pcl_check_token(parser, TOK_NUMBER)) {
        pcl_next_token(parser);
    }
    else if (pcl_check_token(parser, TOK_IDENT)) {
        if (!pcl_set_contains(&parser->symbols, parser->curr_token.text)) {
            pcl_parser_abort("Referencing variable before assignment: %s",
                             parser->curr_token.text);
        }
        pcl_next_token(parser);
    }
    else {
        pcl_parser_abort("Unexpected token at %s", parser->curr_token.text);
    }
}

static void pcl_nl(pcl_parser_t* parser) {
    printf("NEWLINE\n");

    pcl_match(parser, TOK_NEWLINE);

    while (pcl_check_token(parser, TOK_NEWLINE)) {
        pcl_next_token(parser);
    }
}